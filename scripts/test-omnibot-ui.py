def find_aapt2() -> Path:
    sdk_root = Path(os.environ.get("ANDROID_SDK_ROOT") or os.environ.get("ANDROID_HOME") or "/opt/android-sdk")
    build_tools = sdk_root / "build-tools"
    if not build_tools.is_dir():
        raise ToolchainError(f"no build-tools under {sdk_root}; aapt2 is needed for the test APK")
    candidates = sorted((p / "aapt2" for p in build_tools.iterdir() if (p / "aapt2").is_file()),
                        key=lambda p: p.parent.name, reverse=True)
    if not candidates:
        raise ToolchainError(f"no aapt2 in {build_tools}")
    probe = run([str(candidates[0]), "version"])
    if probe.returncode:
        raise ToolchainError(f"{candidates[0]} does not run: {probe.stdout.strip()[:300]}")
    return candidates[0]


# ── same-package constants copied from heavy siblings ────────────────────────
def write_package_constants(target: Path, sources: list[Path]) -> list[str]:
    """Copy same-package `internal const val` declarations out of files that are
    too dependency-heavy to compile here, after proving the real declaration and
    its literal still exist. Not a substitute for UI code: only a constant."""
    compiled_files = set()
    for source in sources:
        try:
            compiled_files.add(source.relative_to(APP / "src").as_posix())
        except ValueError:
            continue
    emitted, missing = [], []
    for consumer, declaration, name, literal in PACKAGE_CONSTANTS:
        if not (APP / "src" / consumer).is_file():
            continue
        decl_rel = declaration[len("main/java/"):]
        if f"main/java/{decl_rel}" in compiled_files:
            continue  # the real declaration file is compiled; no copy needed
        real = APP / "src" / declaration
        if not real.is_file():
            raise ToolchainError(f"{declaration} vanished but {consumer} still needs {name}")
        text = real.read_text(encoding="utf-8", errors="replace")
        match = re.search(rf'internal const val {name}\s*=\s*"([^"]*)"', text)
        if match is None:
            raise ToolchainError(f"{declaration} no longer declares internal const val {name}")
        if match.group(1) != literal:
            raise ToolchainError(f"{name} changed from {literal!r} to {match.group(1)!r}")
        emitted.append((decl_rel.rsplit("/", 1)[0].replace("/", "."), name, literal))
    if not emitted:
        return []
    lines = [f"package {emitted[0][0]}", "",
             "/** Generated by test-omnibot-ui.py: declarations verified against their real files. */"]
    lines += [f'internal const val {name} = "{literal}"' for _, name, literal in emitted]
    target.write_text("\n".join(lines) + "\n", encoding="utf-8")
    return [name for _, name, _ in emitted]


# ── in-app source index (import closure) ─────────────────────────────────────
PACKAGE_RE = re.compile(r"^package\s+([\w.]+)", re.M)
TOP_DECL_RE = re.compile(
    r"^(?:@\w+(?:\([^)]*\))?\s*)*"
    r"(?:(?:public|internal|private|protected|abstract|open|sealed|data|enum|annotation|"
    r"value|inline|operator|infix|suspend|external|final|override|const|lateinit|tailrec)\s+)*"
    r"(?:fun|class|object|interface|val|var|typealias)\s+(?:<[^>\n]*>\s*)?([A-Za-z_]\w*)", re.M)


class SourceIndex:
    """package/symbol → source file map over the app module, built once."""

    def __init__(self, root: Path):
        self.files: dict[str, Path] = {}
        self.package_of: dict[str, str] = {}
        self.decls: dict[str, set[str]] = {}
        self.by_package: dict[str, set[str]] = {}
        self.by_dir: dict[str, set[str]] = {}
        for path in sorted(root.rglob("*.kt")):
            rel = path.relative_to(root).as_posix()
            text = path.read_text(encoding="utf-8", errors="replace")
            package = PACKAGE_RE.search(text)
            if not package:
                continue
            self.files[rel] = path
            self.package_of[rel] = package.group(1)
            self.by_package.setdefault(package.group(1), set()).add(rel)
            self.by_dir.setdefault(rel.rsplit("/", 1)[0] if "/" in rel else "", set()).add(rel)
            self.decls[rel] = set(TOP_DECL_RE.findall(text))

    def resolve_import(self, fq: str) -> tuple[set[str], str]:
        """Map an `import com.openminis.app.…` to declaring files."""
        if fq.endswith(".*"):
            package = fq[:-2]
            hits = self.by_package.get(package, set())
            return set(hits), f"package {package}"
        parts = fq.split(".")
        for cut in range(len(parts) - 1, 3, -1):
            package = ".".join(parts[:cut])
            symbol = parts[cut]
            files = self.by_package.get(package, set())
            if not files:
                continue
            hits = {rel for rel in files if symbol in self.decls.get(rel, set())}
            if hits:
                return hits, f"{package}.{symbol}"
        return set(), ""

    def declaration_file(self, symbol: str, package: str) -> str | None:
        for rel in self.by_package.get(package, set()):
            if symbol in self.decls.get(rel, set()):
                return rel
        return None

# ── compile scope discovery + dependency closure ─────────────────────────────
APP_SRC_PREFIX = "main/java/com/openminis/app/"


def rel_main(app_rel: str) -> str:
    return app_rel[len(APP_SRC_PREFIX):] if app_rel.startswith(APP_SRC_PREFIX) else app_rel


def app_rel(main_rel: str) -> str:
    return APP_SRC_PREFIX + main_rel


def discovered_modules() -> list[tuple[str, str]]:
    """Every production module the extension globs match, as main-relative paths."""
    found: dict[str, str] = {}
    for pattern, why in DISCOVERY_GLOBS:
        for hit in sorted(MAIN.glob(pattern)):
            if hit.is_file():
                found.setdefault(hit.relative_to(MAIN).as_posix(), why)
    return sorted(found.items())


def import_closure(index: SourceIndex, seeds: dict[str, str]) -> tuple[dict[str, str], list[str]]:
    """Close the seed set over in-app imports; return (scope, violations)."""
    scope = dict(seeds)
    violations: list[str] = []
    queue = list(seeds)
    while queue:
        current = queue.pop()
        path = index.files.get(current)
        if path is None:
            continue
        text = path.read_text(encoding="utf-8", errors="replace")
        for fq in re.findall(r"^import\s+(com\.openminis\.app\.[\w.]+)", text, re.M):
            hits, what = index.resolve_import(fq)
            if not hits:
                continue
            for rel in hits:
                if rel in scope:
                    continue
                if not rel.startswith(ALLOWED_DEP_PREFIXES):
                    violations.append(f"{rel} (needed by {current} via {what})")
                    continue
                scope[rel] = f"dependency of {current}"
                queue.append(rel)
    return scope, sorted(set(violations))


def test_import_closure(index: SourceIndex, scope: dict[str, str],
                        test_paths: list[Path]) -> list[str]:
    """Pull in the production files that the *test* sources import.

    A render test that names `ui.settings.SettingsRow` needs that real file in
    the compile set; without this the failure would look like a broken test
    instead of a missing scope entry.
    """
    added: list[str] = []
    pending = list(test_paths)
    seen: set[str] = set()
    while pending:
        path = pending.pop()
        text = path.read_text(encoding="utf-8", errors="replace")
        for fq in re.findall(r"^import\s+(com\.openminis\.app\.[\w.]+)", text, re.M):
            hits, _what = index.resolve_import(fq)
            for rel in hits:
                if rel in scope or rel in seen:
                    continue
                seen.add(rel)
                if not rel.startswith(ALLOWED_DEP_PREFIXES):
                    log(f"[omnibot-ui] test import outside the presentation layer: {rel} (from {path.name})")
                    continue
                scope[rel] = f"imported by test {path.name}"
                added.append(rel)
                pending.append(index.files[rel])
    return added


def compile_units(subset: dict[str, str], test_classes: list[tuple[str, str]]) -> list[tuple[str, str]]:
    return sorted(subset.items())


# ── test discovery (mirrors scripts/verify-ui-test-reports.py) ───────────────
TEST_PACKAGE_RE = re.compile(r"^package\s+([\w.]+)", re.M)
TEST_CLASS_RE = re.compile(r"^(?:public\s+|internal\s+)?(?:class|object)\s+(\w*Omni\w*Test)\b", re.M)


def discover_tests() -> list[tuple[str, str, str]]:
    """Every checked-in *Omni*Test.kt top-level class, as (fqn, source rel, file)."""
    found: list[tuple[str, str, str]] = []
    for path in sorted(TEST.rglob("*Omni*Test.kt")):
        text = path.read_text(encoding="utf-8", errors="replace")
        package = TEST_PACKAGE_RE.search(text)
        if not package:
            continue
        for name in TEST_CLASS_RE.findall(text):
            found.append((f"{package.group(1)}.{name}", path.relative_to(APP / "src").as_posix(), str(path)))
    return sorted(found)


def test_rel(app_rel_path: str) -> str:
    return app_rel_path[len("test/java/com/openminis/app/"):]


def run(cmd: list[str], timeout: int = 1800) -> subprocess.CompletedProcess:
    return subprocess.run(cmd, text=True, stdout=subprocess.PIPE, stderr=subprocess.STDOUT,
                          timeout=timeout,
                          env={**os.environ, "LANG": "C.UTF-8", "LC_ALL": "C.UTF-8"})


UNRESOLVED = re.compile(r"^(?P<file>.+?\.kt):(?P<line>\d+):\d+: error: unresolved reference '?(?P<symbol>[\w.]+)'?",
                        re.M)


def main() -> int:
    parser = argparse.ArgumentParser(
        description="Real Kotlin/Compose compile + Omni*Test execution for the OmniBot UI port")
    parser.add_argument("--keep", action="store_true", help="keep the compilation work directory")
    parser.add_argument("--verbose", action="store_true", help="print toolchain jar paths and full commands")
    parser.add_argument("--motion-only", action="store_true", help="compile/run only OmniMotion + its test")
    parser.add_argument("--compile-only", action="store_true",
                        help="compile the scope and the tests, but do not execute them")
    parser.add_argument("--work-root", default=str(DEFAULT_WORK_ROOT),
                        help=f"temp root (default {DEFAULT_WORK_ROOT}); only this run's child is removed")
    parser.add_argument("--deps-root", default=os.environ.get("MINIS_OMNIBOT_DEPS", str(DEFAULT_LOCAL_DEPS)),
                        help=f"local Robolectric/Compose-test runtime bundle (default {DEFAULT_LOCAL_DEPS})")
    parser.add_argument("--log-dir", default=None, help="write raw compile/test output here too")
    parser.add_argument("--list-scope", action="store_true", help="print the discovered compile scope and exit")
    parser.add_argument("--probe", action="store_true",
                        help="PROBE MODE: compile a copy of a file whose only error is a missing import, "
                             "with that import added, to localise the defect. Production file untouched.")
    args = parser.parse_args()

    if not MAIN.is_dir():
        log(f"FAIL missing app sources under {MAIN}")
        return 1

    index = SourceIndex(MAIN_ROOT / "com" / "openminis" / "app")
    seeds: dict[str, str] = {}
    for app_path, why in CORE_SUBSET:
        seeds[rel_main(app_path)] = f"core subset: {why}"
    for main_rel, why in discovered_modules():
        seeds.setdefault(main_rel, f"discovered: {why}")
    if args.motion_only:
        seeds = {k: v for k, v in seeds.items() if k.endswith(("OmniMotion.kt", "ProviderConfig.kt"))}

    missing = [rel for rel in seeds if not (MAIN / rel).is_file()]
    if missing:
        log("FAIL missing subset sources:")
        for rel in missing:
            log(f"  - src/main/java/com/openminis/app/{rel}")
        return 1

    scope, violations = import_closure(index, seeds)
    if violations:
        log("FAIL compile scope cannot be closed inside the presentation layer:")
        for line in violations:
            log(f"  - {line}")
        log("  -> a presentation module now depends on a business/data package; "
            "either move the dependency behind a parameter or extend ALLOWED_DEP_PREFIXES deliberately")
        return 1

    tests = discover_tests()
    if args.motion_only:
        tests = [t for t in tests if t[0].endswith("OmniMotionTest")]
    if not tests:
        log("FAIL no *Omni*Test classes found: the render/regression suite must not be empty")
        return 1

    test_added = test_import_closure(index, scope, [Path(path) for _, _, path in tests])
    if test_added:
        log(f"[omnibot-ui] test imports pull {len(test_added)} production file(s): {', '.join(test_added)}")

    log(f"[omnibot-ui] compile scope: {len(scope)} production files "
        f"({sum(1 for r in scope if r in seeds)} declared/discovered, {sum(1 for r in scope if r not in seeds)} closure)")
    for rel in sorted(scope):
        log(f"    {rel}  <- {scope[rel]}")
    log(f"[omnibot-ui] test classes: {len(tests)}")
    for fqn, src, _ in tests:
        log(f"    {fqn}  ({src})")
    if args.list_scope:
        return 0

    try:
        jdk = find_jdk([os.environ.get("MINIS_OMNIBOT_JDK", ""), os.environ.get("JAVA_HOME", "")])
        java = jdk / "bin" / "java"
        javac = jdk / "bin" / "javac"
        compiler_cp, stdlib = kotlin_compiler_classpath()
        compose = compose_plugin()
        serialize = serialization_plugin() if not args.motion_only else None
        android = android_jar()
        deps = (ui_jars() + junit_jars() + serialization_runtime()
                + [coroutines_runtime(), androidx_collection_runtime(), stdlib])
        render_jars, android_all = render_runtime(Path(args.deps_root))
    except ToolchainError as error:
        log(f"TOOLCHAIN ERROR: {error}")
        return 2

    work_root = Path(args.work_root)
    work_root.mkdir(parents=True, exist_ok=True)
    work = Path(tempfile.mkdtemp(prefix="compile-", dir=work_root))
    log(f"[omnibot-ui] JDK        {jdk}")
    log(f"[omnibot-ui] kotlinc    {KOTLIN_VERSION}")
    log(f"[omnibot-ui] compose    {compose.name}")
    log(f"[omnibot-ui] android    {android}")
    log(f"[omnibot-ui] robolectric {android_all.name}")
    log(f"[omnibot-ui] work       {work}")
    if args.verbose:
        for path in compiler_cp + deps + render_jars + [compose] + ([serialize] if serialize else []):
            log(f"    jar {path}  sha256={sha256(path)[:16]}")

    status = 0
    transcript: list[str] = []
    try:
        classes = work / "classes"
        classes.mkdir()
        lib_r_classes = work / "lib-r"
        lib_r_classes.mkdir()
        try:
            aapt2 = find_aapt2()
            apk, gen_dir, test_config_dir = build_test_apk(work, aapt2, android, work_root / ".res-cache")
        except ToolchainError as error:
            log(f"TOOLCHAIN ERROR: {error}")
            return 2
        log(f"[omnibot-ui] test apk   {apk.name} (package com.openminis.app, "
            f"declares androidx.activity.ComponentActivity like the merged test manifest)")
        r_sources = sorted(gen_dir.rglob("R.java"))
        if not r_sources:
            log("FAIL aapt2 linked the test APK but generated no R classes")
            return 2
        javac_cmd = [str(javac), "-nowarn", "-classpath", str(android), "-d", str(lib_r_classes),
                     *map(str, r_sources)]
        result = run(javac_cmd)
        transcript.append(result.stdout)
        if result.returncode:
            log("FAIL compiling the R classes generated from the linked resource table:")
            log(result.stdout.strip())
            return 2
        log(f"[omnibot-ui] R classes  {len(r_sources)} packages generated from the linked resource table "
            f"({sum(1 for _ in (work / 'R.txt').read_text().splitlines())} symbols)")

        sources = [MAIN / rel for rel in sorted(scope)]
        if args.probe:
            patched = []
            for source in sources:
                text = source.read_text(encoding="utf-8", errors="replace")
                if re.search(r"\b\d+\.dp\b", text) and "import androidx.compose.ui.unit.dp" not in text:
                    copy = work / ("probe-" + source.name)
                    text = text.replace("import androidx.compose.ui.unit.sp",
                                        "import androidx.compose.ui.unit.sp\nimport androidx.compose.ui.unit.dp", 1)
                    copy.write_text(text, encoding="utf-8")
                    log(f"[omnibot-ui] PROBE PATCH {source.name}: added missing 'import androidx.compose.ui.unit.dp' "
                        f"to a COPY; the production file is still broken")
                    patched.append(copy)
                else:
                    patched.append(source)
            sources = patched
        for fqn, src, path in tests:
            sources.append(Path(path))
            log(f"[omnibot-ui] test source src/{src}")
        constant_names = write_package_constants(work / "PackageConstants.kt", sources)
        if constant_names:
            log(f"[omnibot-ui] const copy  {', '.join(constant_names)} (verified against real declarations)")
            sources.append(work / "PackageConstants.kt")

        classpath = os.pathsep.join(map(str, [android, lib_r_classes] + deps + render_jars))
        plugins = [f"-Xplugin={compose}"] + ([f"-Xplugin={serialize}"] if serialize else [])
        compile_cmd = [str(java), "-Xmx2g", "-cp", os.pathsep.join(map(str, compiler_cp)),
                       "org.jetbrains.kotlin.cli.jvm.K2JVMCompiler",
                       "-no-stdlib", "-no-reflect", "-jvm-target", "17",
                       *plugins,
                       "-classpath", classpath, "-d", str(classes),
                       *map(str, sources)]
        if args.verbose:
            log("    " + " ".join(compile_cmd))
        log(f"[omnibot-ui] compiling {len(sources)} sources ({len(scope)} production + {len(tests)} test)")
        result = run(compile_cmd)
        output = result.stdout
        transcript.append(output)
        for _round in range(4):
            errors = [line for line in output.splitlines() if ": error:" in line]
            if result.returncode == 0 and not errors:
                break
            repaired = repair_scope(errors, scope, index, work)
            if not repaired:
                break
            added = [rel for rel in repaired if rel not in scope]
            if added:
                log(f"[omnibot-ui] closure repair round {_round + 1}: +{len(added)} file(s) "
                    f"{', '.join(added)}")
                for rel in added:
                    scope[rel] = "closure repair (unresolved reference)"
                sources = [MAIN / rel for rel in sorted(scope) if (MAIN / rel).is_file()] + \
                          [Path(path) for _, _, path in tests]
                if (work / "PackageConstants.kt").exists():
                    sources.append(work / "PackageConstants.kt")
                compile_cmd = compile_cmd[:compile_cmd.index("-d")] + ["-d", str(classes)] + \
                    [str(s) for s in sources]
                result = run(compile_cmd)
                output = result.stdout
                transcript.append(output)
            if repaired and not added:
                # a constant copy was emitted; recompile once more with it included
                sources = [MAIN / rel for rel in sorted(scope) if (MAIN / rel).is_file()] + \
                          [Path(path) for _, _, path in tests] + [work / "PackageConstants.kt"]
                compile_cmd = compile_cmd[:compile_cmd.index("-d")] + ["-d", str(classes)] + \
                    [str(s) for s in sources]
                result = run(compile_cmd)
                output = result.stdout
                transcript.append(output)
        errors = [line for line in output.splitlines() if ": error:" in line]
        if result.returncode or errors:
            log("FAIL Kotlin/Compose compilation")
            log("\n".join(errors) if errors else output.strip())
            return 1
        warnings = [line for line in output.splitlines() if ": warning:" in line]
        log(f"[omnibot-ui] compile OK ({len(warnings)} warnings)")

        absent = [name for name in EXPECTED_CLASSES if not (classes / name).is_file()]
        if absent:
            log("FAIL expected class outputs missing (compilation silently incomplete):")
            for name in absent:
                log(f"  - {name}")
            return 1
        log(f"[omnibot-ui] class output verified ({len(EXPECTED_CLASSES)} representative classes)")

        class_outputs = sorted(p.name for p in classes.rglob("*.class"))
        for fqn, _, _ in tests:
            expected = fqn.replace(".", "/") + ".class"
            if not (classes / expected).is_file():
                log(f"FAIL test class was not compiled: {fqn}")
                return 1
        log(f"[omnibot-ui] {len(class_outputs)} class files produced")

        if args.compile_only:
            log("[omnibot-ui] compile-only: skipping execution by request")
            return 0

        run_cp = os.pathsep.join(map(str, [classes, test_config_dir, lib_r_classes, android] + deps + render_jars))
        fqns = [fqn for fqn, _, _ in tests]
        log(f"[omnibot-ui] running JUnit: {len(fqns)} class(es)")
        test = run([str(java), "-cp", run_cp,
                    "-Drobolectric.offline=true",
                    f"-Drobolectric.dependency.dir={android_all.parent}",
                    "-Drobolectric.logging.enabled=false",
                    "-Drobolectric.graphicsMode=LEGACY",
                    "-Drobolectric.sqliteMode=LEGACY",
                    "org.junit.runner.JUnitCore", *fqns])
        transcript.append(test.stdout)
        log(test.stdout.strip())
        if test.returncode:
            log("FAIL JUnit")
            status = 1
        else:
            log(f"[omnibot-ui] PASS compile + {len(fqns)} test class(es)")
        return status
    finally:
        if args.log_dir:
            log_dir = Path(args.log_dir)
            log_dir.mkdir(parents=True, exist_ok=True)
            (log_dir / "omnibot-ui-verify-raw.log").write_text(
                f"kotlinc={KOTLIN_VERSION} compose={compose.name} android={android}\n\n"
                + "\n\n".join(transcript), encoding="utf-8")
        if not args.keep:
            shutil.rmtree(work, ignore_errors=True)
            try:
                work_root.rmdir()  # only removes it when this run left nothing behind
            except OSError:
                pass
        else:
            log(f"[omnibot-ui] kept work dir {work}")


def repair_scope(errors: list[str], scope: dict[str, str], index: SourceIndex, work: Path) -> list[str]:
    """Map `unresolved reference` diagnostics back to real declaring files.

    Handles production and test owners alike: a test that names
    `ui.settings.SettingsRow` pulls the real declaring file in, exactly like a
    production import would. Returns the files added to the scope (empty when
    nothing could be repaired) and writes a verified constant copy when the
    symbol is a same-package `const val` owned by a file too heavy to compile.
    """
    added: list[str] = []
    constants_target = work / "PackageConstants.kt"
    copied: dict[str, list[str]] = {}
    for line in errors:
        match = UNRESOLVED.search(line)
        if not match:
            continue
        symbol = match.group("symbol").split(".")[0]
        declaring = Path(match.group("file"))
        if not declaring.is_absolute():
            declaring = ROOT / declaring
        owner_rel, package = "", ""
        for base, prefix in ((MAIN, ""), (TEST, "")):
            try:
                owner_rel = declaring.relative_to(base).as_posix()
            except ValueError:
                continue
            package = f"com.openminis.app.{owner_rel.rsplit('/', 1)[0].replace('/', '.')}"
            break
        if not owner_rel:
            continue
        candidate = index.declaration_file(symbol, package)
        if candidate is None or candidate in scope:
            continue
        if not candidate.startswith(ALLOWED_DEP_PREFIXES):
            log(f"[omnibot-ui] cannot repair: {symbol} lives in {candidate}, outside the presentation layer")
            continue
        text = index.files[candidate].read_text(encoding="utf-8", errors="replace")
        literal = re.search(rf'internal const val {symbol}\s*=\s*"([^"]*)"', text)
        if literal is not None:
            copied.setdefault(package, []).append(f'internal const val {symbol} = "{literal.group(1)}"')
            log(f"[omnibot-ui] const copy  {symbol} (re-declared from {candidate} after unresolved reference)")
            continue
        scope[candidate] = f"closure repair for {symbol} (used by {owner_rel})"
        added.append(candidate)
    if copied:
        existing = constants_target.read_text().splitlines() if constants_target.exists() else []
        lines = existing[:] if existing else []
        for package, decls in copied.items():
            if not lines:
                lines = [f"package {package}", "",
                         "/** Generated by test-omnibot-ui.py from real declarations. */"]
            lines += [d for d in decls if d not in lines]
        constants_target.write_text("\n".join(lines) + "\n", encoding="utf-8")
    return added



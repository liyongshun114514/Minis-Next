def render_runtime(local_deps: Path) -> tuple[list[Path], Path]:
    """Robolectric + Compose-test runtime and the offline android-all jar."""
    classpath_file = local_deps / "runtime-classpath.txt"
    extras_file = local_deps / "extra-jars" / "classpath.txt"
    if not classpath_file.is_file():
        raise ToolchainError(
            f"no Robolectric/Compose-test runtime bundle at {classpath_file}; the render leg needs the "
            "local bundle assembled from the Gradle cache (CI runs the same classes through Gradle)")
    jars = [Path(line.strip()) for line in classpath_file.read_text().splitlines() if line.strip()]
    if extras_file.is_file():
        jars += [Path(line.strip()) for line in extras_file.read_text().splitlines() if line.strip()]
    absent = [str(jar) for jar in jars if not jar.is_file()]
    if absent:
        raise ToolchainError(f"runtime bundle references missing jars: {absent[:5]}")
    android_all = sorted((local_deps / "android-all").glob("android-all-instrumented-*.jar"))
    if not android_all:
        raise ToolchainError(
            f"no android-all-instrumented jar under {local_deps / 'android-all'}; "
            f"Robolectric cannot start SDK {ROBOLECTRIC_SDK} offline without it")
    return jars, android_all[-1]



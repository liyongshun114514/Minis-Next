#!/usr/bin/env python3
"""Real Kotlin/Compose compilation + real JVM/Robolectric execution for the OmniBot UI port.

Why this exists
---------------
Gradle is the authority (`.github/workflows/android-ubuntu.yml` runs
`:app:testGithubDebugUnitTest --tests '*Omni*Test'` and
`scripts/verify-ui-test-reports.py`). This script is the *local* equivalent that
runs without Gradle, without a device and without network, so a change can be
proved before pushing. It compiles the production Kotlin of the port with the
Kotlin 2.1.0 compiler and Compose compiler plugin from the local Gradle cache
against the real Compose 1.9.1 / Material3 1.3.2 jars, then executes the checked
in `*Omni*Test` classes on a JVM — the Robolectric ones really inflate the
composables, really lay them out and really dispatch taps, drags and focus.

Compile scope: extension mechanism, not a frozen list
-----------------------------------------------------
A new presentation module is picked up automatically when it matches
`DISCOVERY_GLOBS` (`ui/**/Omni*.kt`, `ui/chat/ChatComposerMotion*.kt`). Every
match is then closed over its in-app dependencies (import closure), so a module
that uses `OmniColors`, `OmniShapes` or `OmniMorphSpec` compiles through the
real declarations. Two hard rules keep this honest:

* every glob match must end up in the compile set — a module that cannot be
  closed inside the allowed packages fails the run instead of being skipped;
* a same-package `const val` that lives in a file too dependency-heavy to
  compile may be copied, but only after its real declaration and literal are
  re-read from the source file (see `PACKAGE_CONSTANTS`).

Stub boundary (explicit, nothing more is faked)
-----------------------------------------------
* `android.jar` is the SDK's compile-only stub: `android.*` resolves at compile
  time and is provided by Robolectric's real Android runtime at test time.
* The Robolectric test APK is linked with aapt2 from the app's real
  `src/main/res` plus the resource directories of the AndroidX libraries under
  test (`RES_AARS`). `R` is generated by aapt2 from that linked table, so a
  `R.string` id used by a test is the id the runtime really has — no invented
  ids, and a renamed or deleted string breaks the compile instead of being
  absorbed. Robolectric needs this APK to resolve the app package, its
  activities and its resources; CI gets the same file from AGP.
* Robolectric cannot run its native graphics runtime on Linux/aarch64
  (`DefaultNativeRuntimeLoader` refuses), so the local run pins
  `robolectric.graphicsMode=LEGACY` / `sqliteMode=LEGACY`. CI uses NATIVE. Tests
  therefore assert nodes, callbacks, state and semantics — never pixels,
  screenshots or exact glyph metrics.

What is proven / what is NOT
----------------------------
Proven: the ported files type-check against the real Compose API, they compile
into the expected classes, and the `*Omni*Test` classes execute green including
real composition, tap/drag/focus dispatch, sheet show/hide, recomposition on
theme change and window-size changes.
NOT proven: pixel parity with the reference implementation, GPU glass effects
(Legacy graphics cannot render RenderEffect), device-only behaviour.

Usage:
  scripts/test-omnibot-ui.py [--keep] [--verbose] [--motion-only]
                             [--compile-only] [--work-root DIR] [--log-dir DIR]
                             [--probe] [--list-scope]

Exit codes: 0 = compile + all tests passed, 1 = compile/test failure,
            2 = toolchain/environment problem (never counted as a pass).
"""


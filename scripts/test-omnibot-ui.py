def res_digest(root: Path) -> str:
    digest = hashlib.sha256()
    for path in sorted(root.rglob("*")):
        if path.is_file():
            stat = path.stat()
            digest.update(f"{path.relative_to(root).as_posix()}:{stat.st_size}:{stat.st_mtime_ns}".encode())
    return digest.hexdigest()[:16]


def compile_res_dir(aapt2: Path, res: Path, out_zip: Path, cache: Path | None) -> Path | None:
    """aapt2-compile one resource directory, reusing a content-keyed cache."""
    if not res.is_dir():
        return None
    key = f"{out_zip.stem}-{res_digest(res)}.zip"
    cached = (cache / key) if cache else None
    if cached is not None and cached.is_file():
        out_zip.write_bytes(cached.read_bytes())
        return out_zip
    result = run([str(aapt2), "compile", "--dir", str(res), "-o", str(out_zip)])
    if result.returncode or not out_zip.is_file():
        raise ToolchainError(f"aapt2 could not compile {res}: {result.stdout.strip()[:400]}")
    if cached is not None:
        cache.mkdir(parents=True, exist_ok=True)
        cached.write_bytes(out_zip.read_bytes())
    return out_zip


def build_test_apk(work: Path, aapt2: Path, android: Path, cache: Path | None) -> tuple[Path, Path, Path]:
    """Build the Robolectric test APK plus its real `R` classes.

    Robolectric resolves the app package and its activities from a linked APK
    (`AndroidManifest.getApkFile()`); without one it falls back to the synthetic
    `org.robolectric.default` package, in which `androidx.activity.ComponentActivity`
    cannot be resolved and every `createComposeRule()` test fails before it
    starts. Gradle hands the APK over in `/com/android/tools/test_config.properties`;
    the harness links the same APK with aapt2 — including the real resources —
    and generates `R` from the linked table, so `R.string` ids are the ones the
    runtime actually has (no invented ids anywhere).
    """
    manifest = work / "AndroidManifest.xml"
    manifest.write_text(TEST_MANIFEST, encoding="utf-8")
    flat = work / "flat"
    flat.mkdir()
    archives = []
    compiled = compile_res_dir(aapt2, RES, flat / "app.zip", cache)
    if compiled is None:
        raise ToolchainError(f"the app has no resources at {RES}")
    archives.append(compiled)
    packages = []
    for pattern, why in RES_AARS:
        hits = sorted(GRADLE_CACHE.glob(pattern))
        if not hits:
            raise ToolchainError(f"no cached AAR for {pattern} ({why})")
        aar = hits[-1]
        import zipfile

        with zipfile.ZipFile(aar) as zf:
            if "AndroidManifest.xml" not in zf.namelist():
                continue
            meta = re.search(rb'package="([^"]+)"', zf.read("AndroidManifest.xml"))
            if not meta:
                raise ToolchainError(f"{aar}: no package in AndroidManifest.xml")
            package = meta.group(1).decode()
            res_present = any(name.startswith("res/") for name in zf.namelist())
            if res_present:
                zf.extractall(work / "aar" / package)
        if res_present:
            compiled = compile_res_dir(aapt2, work / "aar" / package / "res",
                                       flat / f"{package}.zip", cache)
            if compiled is not None:
                archives.append(compiled)
                packages.append(package)
    apk = work / "omni-test.apk"
    gen = work / "gen"
    gen.mkdir()
    link = run([str(aapt2), "link", "-o", str(apk), "-I", str(android),
                "--manifest", str(manifest), *map(str, archives),
                "--auto-add-overlay", "--java", str(gen),
                "--extra-packages", ":".join(packages),
                "--output-text-symbols", str(work / "R.txt"),
                "--min-sdk-version", "26", "--target-sdk-version", "35",
                "--version-code", "1", "--version-name", "1"])
    if link.returncode or not apk.is_file():
        raise ToolchainError(f"aapt2 could not link the Robolectric test APK: {link.stdout.strip()[:600]}")
    config_dir = work / "test-config" / "com" / "android" / "tools"
    config_dir.mkdir(parents=True, exist_ok=True)
    (config_dir / "test_config.properties").write_text(
        f"android_merged_manifest={manifest}\n"
        f"android_resource_apk={apk}\n"
        f"android_custom_package=com.openminis.app\n", encoding="utf-8")
    return apk, gen, config_dir.parent.parent.parent

